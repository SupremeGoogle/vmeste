/**
 * Флаг `Secure` для наших cookie.
 *
 * По умолчанию — как положено: в проде только по HTTPS. Но у этого
 * приложения есть законный сценарий без HTTPS — ноутбук координатора,
 * раздающий приложение в зале по локальной сети, когда интернет умер
 * (план Б из PLAN.md §5.1). С `Secure` вход организатора в такой день
 * молча не сработает: браузер примет форму, но cookie не сохранит.
 *
 * Поэтому флаг можно снять переменной `COOKIE_SECURE=0` — осознанно,
 * на один вечер и в закрытой сети.
 */
export function cookieSecure(): boolean {
  if (process.env.COOKIE_SECURE === "0") return false;
  return process.env.NODE_ENV === "production";
}
