/**
 * Лимиты на поиск гостя. Настроены по итогам нагрузочной проверки, а не на глаз.
 *
 * Что показала проверка: при лимите 20 запросов в минуту на адрес из 150 гостей
 * проходят 17, остальные получают отказ. Причина — NAT: в зале все сидят
 * за одним wi-fi или за одной сотовой вышкой, и с точки зрения сервера
 * это ОДИН адрес. Заголовок x-forwarded-for тут не спасает: он честно
 * возвращает один и тот же внешний адрес для всей свадьбы.
 *
 * Вывод из этого: лимит по адресу — слепой инструмент для нашего сценария.
 * Он оставлен грубым потолком против скриптового перебора (300/мин с адреса
 * и 1200/мин на мероприятие — на два порядка выше живой очереди), а настоящая
 * защита от выгрузки списка гостей встроена в сам поиск:
 *   — запрос короче двух символов не возвращает ничего;
 *   — в ответе максимум 5 совпадений, дальше «уточните фамилию»;
 *   — в ответе только имя и номер стола, ни телефона, ни статуса RSVP;
 *   — каждый поиск пишется в GuestActionLog, перебор виден организатору.
 *
 * Компромисс сознательный: утечка здесь — имена гостей и номера столов,
 * а цена ложного срабатывания — человек, застрявший в дверях зала.
 */
export const PER_CLIENT_LIMIT = 300;
export const PER_EVENT_LIMIT = 1200;
export const WINDOW_MS = 60_000;

export function clientAddress(req: Request): string {
  return (
    req.headers.get("x-forwarded-for")?.split(",")[0]?.trim() ||
    req.headers.get("x-real-ip")?.trim() ||
    "unknown"
  );
}

/** Ключи для двух счётчиков: по клиенту и по мероприятию целиком. */
export function lookupKeys(req: Request, eventId: string) {
  return {
    client: { key: `lookup:${eventId}:${clientAddress(req)}`, limit: PER_CLIENT_LIMIT },
    event: { key: `lookup:${eventId}:all`, limit: PER_EVENT_LIMIT },
  };
}
