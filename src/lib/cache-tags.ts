/**
 * Теги кеша — все в одном файле (PLAN.md §5.7).
 *
 * Агрессивная статика — единственный способ выдержать плохую связь на
 * площадке, и она же даёт классическую жалобу: «я поменял стол, а гость
 * видит старый». Лечится не осторожностью, а сводом правил: тег строится
 * функцией отсюда, строк вида `` `event:${id}` `` в компонентах нет,
 * и рядом с каждым тегом написано, кто его ставит и кто сбрасывает.
 */

/** Блоки приглашения конкретного мероприятия. Ставит `getInviteBlocks`,
 *  сбрасывает конструктор приглашения после любой правки блока. */
export const eventTag = (eventId: string) => `event:${eventId}`;

/** Публичное приглашение по слагу. Тег по слагу, а не по id, потому что
 *  на момент чтения id ещё неизвестен — ищем как раз по слагу. */
export const inviteSlugTag = (slug: string) => `invite:${slug}`;

/** Рассадка: план зала для гостя. Сбрасывается операциями рассадки. */
export const seatingTag = (eventId: string) => `seating:${eventId}`;

/** Всё, что закешировано по одному мероприятию: для кнопки «сбросить кеш»
 *  в панели — спасательный круг в день свадьбы. */
export function allEventTags(eventId: string, slug: string): string[] {
  return [eventTag(eventId), inviteSlugTag(slug), seatingTag(eventId)];
}
