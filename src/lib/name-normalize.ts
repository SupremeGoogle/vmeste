/**
 * Нормализация имён гостей — первый слой поиска на входе в зал (PLAN.md §1.4).
 *
 * Задача: привести «Анастасiя», «АНАСТАСИЯ  Петрова!» и «anastasiya» к общему
 * виду, чтобы триграммный поиск сравнивал сопоставимые строки.
 *
 * Слой 1 (здесь) — детерминированные подмены.
 * Слой 2 — словарь уменьшительных (см. src/server/services/diminutives.ts).
 * Слой 3 — pg_trgm в SQL.
 */

/**
 * Латинские буквы, визуально совпадающие с кириллическими. Ловит два случая:
 * «Анастасiя» (украинская i вместо и) и раскладочные подмены, когда часть
 * имени набрана на английской раскладке.
 */
const LOOKALIKE: Record<string, string> = {
  a: "а",
  b: "в",
  c: "с",
  e: "е",
  h: "н",
  i: "и",
  k: "к",
  m: "м",
  o: "о",
  p: "р",
  t: "т",
  x: "х",
  y: "у",
  "і": "и", // U+0456, украинская i
  "ї": "и",
  "ѐ": "е",
  "ј": "j",
};

/** Полная транслитерация: «Anastasiya» → «анастасия». Применяется только
 *  когда строка целиком латинская — иначе испортит смешанные написания. */
const TRANSLIT: [RegExp, string][] = [
  [/shch/g, "щ"], [/sch/g, "щ"], [/yo/g, "ё"], [/zh/g, "ж"], [/kh/g, "х"],
  [/ts/g, "ц"], [/ch/g, "ч"], [/sh/g, "ш"], [/yu/g, "ю"], [/ya/g, "я"],
  [/iy\b/g, "ий"], [/ye/g, "е"], [/j/g, "й"],
  // «Dmitry» — конечная y это «ий», а не «ы»
  [/y\b/g, "и"],
  [/a/g, "а"], [/b/g, "б"], [/v/g, "в"], [/g/g, "г"], [/d/g, "д"],
  [/e/g, "е"], [/z/g, "з"], [/i/g, "и"], [/y/g, "ы"], [/k/g, "к"],
  [/l/g, "л"], [/m/g, "м"], [/n/g, "н"], [/o/g, "о"], [/p/g, "п"],
  [/r/g, "р"], [/s/g, "с"], [/t/g, "т"], [/u/g, "у"], [/f/g, "ф"],
  [/h/g, "х"], [/c/g, "ц"], [/w/g, "в"], [/x/g, "кс"], [/q/g, "к"],
];

const LATIN_ONLY = /^[a-z\s'\-.]+$/;

/**
 * Приводит имя к ключу поиска.
 * «Анастасiя  Петрова-Иванова!» → «анастасия петрова иванова»
 */
export function normalizeName(input: string): string {
  let s = input.toLowerCase().trim();

  // Юникод-нормализация: отделяет диакритику, чтобы её можно было снять.
  s = s.normalize("NFKD").replace(/[̀-ͯ]/g, "");

  // Целиком латинское написание транслитерируем, иначе — только похожие буквы.
  if (LATIN_ONLY.test(s)) {
    for (const [re, to] of TRANSLIT) s = s.replace(re, to);
  } else {
    s = s.replace(/[a-zіїѐј]/g, (ch) => LOOKALIKE[ch] ?? ch);
  }

  s = s.replace(/ё/g, "е");
  s = s.replace(/й/g, "и"); // «Дмитрий» / «Дмитрии» — частая опечатка при вводе
  s = s.replace(/ъ/g, "ь");
  // «Дмитрий» → «дмитрии» → «дмитри», чтобы совпасть с транслитерацией «Dmitry».
  // \b в JS не работает с кириллицей, поэтому конец слова задан явно.
  s = s.replace(/ии(?=\s|$)/g, "и");

  // Пунктуация и дефисы в разделители: двойные фамилии ищутся по частям.
  s = s.replace(/[^а-я0-9\s]/g, " ");
  s = s.replace(/\s+/g, " ").trim();

  return s;
}

/** Слова ключа поиска. Гость чаще вводит одно слово, чем полное ФИО. */
export function nameTokens(input: string): string[] {
  return normalizeName(input)
    .split(" ")
    .filter((t) => t.length >= 2);
}

/**
 * Готов ли ввод к поиску. Один символ ищет всех подряд и превращает
 * форму входа в выгрузку списка гостей — минимум два.
 */
export function isSearchable(input: string): boolean {
  return normalizeName(input).replace(/\s/g, "").length >= 2;
}
