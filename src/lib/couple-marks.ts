/**
 * Отметки молодожёнов на плане зала.
 *
 * Первый вопрос гостя, вошедшего в зал, — «где мой стол», второй — «а где
 * сидят молодые». Второй вопрос закрывается двумя значками на плане, и
 * рисовать их надо одинаково в пяти местах: редактор рассадки, план в
 * панели, план для гостя строкой, PDF и демо на титульной странице.
 *
 * Поэтому фигуры описаны здесь геометрией, а не картинками: SVG-строка,
 * React-компонент и react-pdf рисуют их одними и теми же координатами.
 * Раньше это были цветок и бабочка-галстук — узнаваемо, но иносказательно:
 * человек, впервые увидевший план, честно спрашивал, что значит кружок с
 * лепестками. Теперь это фигуры людей — невеста в платье с фатой и жених
 * в костюме, — и подписи к ним больше не нужны, хотя они и остались.
 *
 * Почему не эмодзи (👰🤵) и не картинки: эмодзи не переживают PDF (нужен
 * шрифт с ними) и выглядят по-разному на айфоне и на ноутбуке
 * координатора, а картинка — это лишний запрос на странице, где мы
 * считаем килобайты, и серое пятно в чёрно-белой распечатке.
 *
 * Форма описана списком примитивов, а не двумя частными случаями, как
 * было. Каждый рендерер просто проходит по списку — добавить третью роль
 * (свидетель, ребёнок) можно, не трогая пять файлов.
 */
import type { GuestRole } from "@/generated/prisma/enums";

/** Радиус кружка-подложки под значком. */
export const MARK_RADIUS = 13;

/**
 * Роль цвета, а не сам цвет: подложка у значка в панели золотая, в PDF —
 * тоже, но белый там печатный, а на тёмном экране в зале всё иначе.
 * Каждый рендерер подставляет свои три цвета.
 *
 *   ink   — сама фигура, контрастная к подложке;
 *   veil  — полупрозрачная деталь: фата;
 *   hole  — вырез цвета подложки: рубашка под пиджаком.
 */
export type MarkTone = "ink" | "veil" | "hole";

export type MarkShape =
  | { kind: "circle"; cx: number; cy: number; r: number; tone: MarkTone }
  | { kind: "path"; d: string; tone: MarkTone }
  | { kind: "polygon"; points: string; tone: MarkTone };

export type Mark = {
  /** Порядок важен: фата рисуется под платьем, бабочка поверх рубашки. */
  shapes: MarkShape[];
  /** Подпись для доступности и легенды. */
  label: string;
};

/**
 * Значок роли в собственных координатах: центр в (0,0), фигура вписана
 * в круг радиуса 13. Вызывающий переносит её к месту гостя.
 *
 * Числа подобраны под размер 26 px — столько занимает значок в редакторе.
 * На этом размере голова меньше 2 единиц сливается с плечами, а платье
 * уже 10 перестаёт отличаться от костюма; проверено глазом, а не теорией.
 */
export function markFor(role: GuestRole): Mark | null {
  if (role === "BRIDE") {
    return {
      label: "невеста",
      shapes: [
        // Фата: накидка вокруг головы, спадающая до подола. Рисуется
        // первой и полупрозрачной — иначе она съедает силуэт платья.
        {
          kind: "path",
          tone: "veil",
          d: "M0,-9.2 C-4.8,-9.2 -7,-4.2 -7.6,9 L-4.9,9 C-5.3,-2.4 -3.1,-6.8 0,-6.8 C3.1,-6.8 5.3,-2.4 4.9,9 L7.6,9 C7,-4.2 4.8,-9.2 0,-9.2 Z",
        },
        // Платье колоколом: узкое в талии, широкое у пола.
        {
          kind: "path",
          tone: "ink",
          d: "M-2.3,-3.3 C-3.7,-2 -5.1,3 -5.7,9 L5.7,9 C5.1,3 3.7,-2 2.3,-3.3 Z",
        },
        { kind: "circle", cx: 0, cy: -5.9, r: 2.5, tone: "ink" },
      ],
    };
  }

  if (role === "GROOM") {
    return {
      label: "жених",
      shapes: [
        // Пиджак: прямые плечи и ровный низ — противоположность колоколу.
        {
          kind: "path",
          tone: "ink",
          d: "M-2.3,-3.3 C-4.9,-2.5 -6.1,0.4 -6.1,9 L6.1,9 C6.1,0.4 4.9,-2.5 2.3,-3.3 Z",
        },
        // Рубашка треугольником — вырез цвета подложки, читается как лацканы.
        { kind: "path", tone: "hole", d: "M-3.1,-3.4 L3.1,-3.4 L0,3.6 Z" },
        // Бабочка поверх рубашки: два треугольника, сходящиеся к узлу.
        { kind: "polygon", tone: "ink", points: "-2.4,-3.8 -0.4,-2.6 -2.4,-1.4" },
        { kind: "polygon", tone: "ink", points: "2.4,-3.8 0.4,-2.6 2.4,-1.4" },
        { kind: "circle", cx: 0, cy: -2.6, r: 0.75, tone: "ink" },
        { kind: "circle", cx: 0, cy: -5.9, r: 2.5, tone: "ink" },
      ],
    };
  }

  return null;
}

/** Человеческие названия ролей — для форм и легенды. */
export const ROLE_LABEL: Record<GuestRole, string> = {
  GUEST: "гость",
  BRIDE: "невеста",
  GROOM: "жених",
};

/** Есть ли на плане кто-то из молодожёнов: легенда рисуется только тогда. */
export function hasCouple(roles: GuestRole[]): boolean {
  return roles.some((role) => role !== "GUEST");
}
