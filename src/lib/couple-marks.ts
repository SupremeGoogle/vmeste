/**
 * Отметки молодожёнов на плане зала.
 *
 * Первый вопрос гостя, вошедшего в зал, — «где мой стол», второй — «а где
 * сидят молодые». Второй вопрос закрывается двумя значками на плане, и
 * рисовать их надо одинаково в четырёх местах: редактор рассадки, план
 * для гостя, PDF и печатная страница. Поэтому фигуры описаны здесь
 * геометрией, а не картинками: SVG-строка, React-компонент и react-pdf
 * рисуют их одними и теми же координатами.
 *
 * Почему не эмодзи (👰🤵) и не картинки: эмодзи не переживают PDF (нужен
 * шрифт с ними) и выглядят по-разному на айфоне и на ноутбуке
 * координатора, а картинка — это лишний запрос на странице, где мы
 * считаем килобайты.
 *
 * Фигуры выбраны узнаваемые в мелком размере и в чёрно-белой печати:
 * букет (пять лепестков вокруг сердцевины) и бабочка-галстук.
 */
import type { GuestRole } from "@/generated/prisma/enums";

/** Радиус кружка-подложки под значком. */
export const MARK_RADIUS = 13;

export type Mark = {
  /** Что рисуем внутри кружка. */
  petals?: { x: number; y: number; r: number }[];
  /** Бабочка: два треугольника и узел. */
  bow?: { left: string; right: string; knot: { x: number; y: number; r: number } };
  /** Подпись для доступности и легенды. */
  label: string;
};

/**
 * Значок роли в собственных координатах: центр в (0,0), радиус ~9.
 * Вызывающий переносит фигуру к месту гостя.
 */
export function markFor(role: GuestRole): Mark | null {
  if (role === "BRIDE") {
    const petals = [0, 1, 2, 3, 4].map((index) => {
      // Пять лепестков по кругу, начиная сверху.
      const angle = (index / 5) * Math.PI * 2 - Math.PI / 2;
      return { x: Math.cos(angle) * 4.2, y: Math.sin(angle) * 4.2, r: 2.9 };
    });
    return { petals: [...petals, { x: 0, y: 0, r: 2.2 }], label: "невеста" };
  }

  if (role === "GROOM") {
    return {
      // Два треугольника, сходящиеся к узлу: слева и справа от центра.
      bow: {
        left: "-7,-4.5 -1.4,0 -7,4.5",
        right: "7,-4.5 1.4,0 7,4.5",
        knot: { x: 0, y: 0, r: 1.9 },
      },
      label: "жених",
    };
  }

  return null;
}

/** Человеческие названия ролей — для форм и легенды. */
export const ROLE_LABEL: Record<GuestRole, string> = {
  GUEST: "гость",
  BRIDE: "невеста",
  GROOM: "жених",
};

/** Есть ли на плане кто-то из молодожёнов: легенда рисуется только тогда. */
export function hasCouple(roles: GuestRole[]): boolean {
  return roles.some((role) => role !== "GUEST");
}
