import { describe, expect, it } from "vitest";
import { isBlockedWish } from "@/lib/wish-moderation";

describe("автоматическая защита пожеланий", () => {
  it.each([
    "Вы идиоты и испортили праздник",
    "Ненавижу вас",
    "Желаю вам развода",
    "Чтоб вы сдохли",
    "Вы мрaзь",
    "Сука, ненавижу вас",
    "Вы уроды",
    "Пусть вы разведетесь",
    "Сдохните оба",
    "Горите в аду",
  ])("блокирует оскорбление или злое пожелание: %s", (message) => {
    expect(isBlockedWish("Гость", message)).toBe(true);
  });

  it("проверяет и подпись автора", () => {
    expect(isBlockedWish("Вы идиоты", "Совет да любовь")).toBe(true);
  });

  it.each([
    "Совет да любовь!",
    "Пусть вам никогда не грозит скука",
    "Пусть все трудности останутся позади",
  ])("не задерживает доброе пожелание: %s", (message) => {
    expect(isBlockedWish("Гость", message)).toBe(false);
  });
});
