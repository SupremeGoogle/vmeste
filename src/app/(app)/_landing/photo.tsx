/**
 * Показ снимка. Без обращения к диску — поэтому годится и на сервере,
 * и внутри клиентских компонентов.
 *
 * Разделение не формальность: `media.ts` читает файловую систему, и
 * стоит такому модулю попасть в клиентский бандл, сборка падает с
 * «does not support external modules (request: node:fs)». Здесь только
 * разметка, путь приходит готовым.
 *
 * Почему не `next/image`: снимки уже подготовлены под свои места, а
 * оптимизатор потянул бы за собой настройку доменов и отдельный маршрут
 * `/_next/image` ради страницы, которая и так отдаётся статикой.
 */

/**
 * Снимок или спокойная заливка на его месте.
 *
 * Пустое место, которое честно говорит, что оно пустое, лучше
 * нарисованного заполнителя: заполнитель однажды уезжает в продакшен и
 * там остаётся.
 */
export function Photo({
  src, alt, className, priority,
}: {
  src: string | null;
  /** Обязателен и без умолчания: это то, что слышит вместо фотографии
   *  человек с экранным диктором, и «изображение» ему не говорит ничего.
   *  Для чисто декоративных подложек передаётся пустая строка. */
  alt: string;
  className?: string;
  /** Первый экран грузится сразу, остальное — по мере прокрутки. */
  priority?: boolean;
}) {
  if (!src) {
    return (
      <span
        className={`flex items-center justify-center bg-gradient-to-br from-stone-100 to-stone-200/60 ${className ?? ""}`}
        aria-hidden="true"
      />
    );
  }

  return (
    <img
      src={src}
      alt={alt}
      loading={priority ? "eager" : "lazy"}
      decoding="async"
      className={`object-cover ${className ?? ""}`}
    />
  );
}
